// `{name}` marks a value filled at runtime: fillText() for plain text (labels, toasts), <Fill> for rich text.

/** The `{name}` placeholders of a template, as a union of names. */
export type Placeholders<T extends string> = T extends `${string}{${infer K}}${infer Rest}` ? K | Placeholders<Rest> : never;

/** Fills every `{name}` in a template. Values never contain markup; this is plain text. */
export function fillText<T extends string>(template: T, values: Record<Placeholders<T>, string | number>): string {
  const map = values as Record<string, string | number>;
  return template.replace(/\{([A-Za-z]+)\}/g, (whole, name: string) => (name in map ? String(map[name]) : whole));
}

